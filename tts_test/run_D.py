# -*- coding: utf-8 -*-
"""D: dots.tts (MeanFlow). Run twice - default voice, and cloning today's af_heart voice."""
import os, json, time, traceback
os.environ.setdefault("CUDA_VISIBLE_DEVICES","1")
import torch, numpy as np, soundfile as sf
BASE="/home/pavlo/lab/tts_test/out"; M="/home/pavlo/lab/tts_test/models"
SAMPLES=json.load(open(BASE+"/samples.json"))
from dots_tts.runtime import DotsTtsRuntime
rt=DotsTtsRuntime.from_pretrained(M+"/dots-mf", precision="bf16")

def _cv(x):
    if hasattr(x,"detach"): x=x.detach().float().cpu()
    return np.asarray(x).astype(np.float32).squeeze()
def audio_of(r):
    for a in ("audio","waveform","wav","samples"):
        if hasattr(r,a): return _cv(getattr(r,a))
    if isinstance(r,(tuple,list)): return _cv(r[0])
    if isinstance(r,dict):
        for a in ("audio","waveform","wav"):
            if a in r: return _cv(r[a])
    raise RuntimeError("unknown result type")
def sr_of(r,d=24000):
    for a in ("sample_rate","sampling_rate","sr"):
        if hasattr(r,a): return int(getattr(r,a))
        if isinstance(r,dict) and a in r: return int(r[a])
    return d

def run(tag, prompt_audio=None, prompt_text=None, note=""):
    OUT=BASE+"/"+tag; os.makedirs(OUT,exist_ok=True)
    torch.cuda.reset_peak_memory_stats(0); rows=[]
    for sid,text in SAMPLES:
        t0=time.time()
        try:
            r=rt.generate(text=text, prompt_audio_path=prompt_audio, prompt_text=prompt_text,
                          language="en", template_name="tts", normalize_text=True)
            a=audio_of(r); sr=sr_of(r)
        except Exception:
            traceback.print_exc(); continue
        g=time.time()-t0; fn=sid+".wav"; sf.write(OUT+"/"+fn,a,sr); dur=len(a)/sr
        rows.append(dict(page=sid,file=tag+"/"+fn,model="dots.tts 2B (MeanFlow)",
            config=("zero-shot clone of today's af_heart voice" if prompt_audio else "default voice, no reference"),
            gen_s=round(g,2),dur_s=round(dur,2),rtf=round(g/dur,3),sr=sr))
        print("%s %s dur %5.2f gen %5.2f rtf %.3f"%(tag,sid,dur,g,g/dur),flush=True)
    v=torch.cuda.max_memory_allocated(0)/2**30
    json.dump(dict(candidate=tag.replace("_"," - ",1),licence="Apache-2.0",notes=note,
        vram_gb=round(v,2),rows=rows),open(OUT+"/results.json","w"),indent=1)
    print("%s peak VRAM %.2f GiB"%(tag,v),flush=True)

try: run("D1_dots.tts-default", note="Cloning model run with no reference clip - voice is arbitrary.")
except Exception: traceback.print_exc()
try:
    ref=BASE+"/A_kokoro/p01.wav"
    run("D2_dots.tts-clone-af_heart", prompt_audio=ref, prompt_text=SAMPLES[0][1],
        note="Same voice identity as production today, generated by a much larger model - the cleanest A/B of engine quality alone.")
except Exception: traceback.print_exc()
print("D_DONE")
